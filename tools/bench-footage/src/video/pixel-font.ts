const GLYPH_WIDTH = 5;
const GLYPH_HEIGHT = 7;
/** One pixel between letters and a one-pixel band around the line. */
const GAP = 1;

export interface TextImage {
  readonly width: number;
  readonly height: number;
  /** Binary PPM (P6): white text on a dark grey band. */
  readonly ppm: Uint8Array;
}

export function textImage(line: string): TextImage {
  const chars = [...line.toUpperCase()];
  const missing = chars.filter((char) => GLYPHS[char] === undefined);
  if (missing.length > 0)
    throw new Error(`no pixel glyph for ${[...new Set(missing)].join(' ')} in '${line}'`);
  const width = chars.length * (GLYPH_WIDTH + GAP) + GAP;
  const height = GLYPH_HEIGHT + 2 * GAP;
  const header = new TextEncoder().encode(`P6\n${width} ${height}\n255\n`);
  const pixels = new Uint8Array(width * height * 3).fill(24);
  chars.forEach((char, index) => {
    const rows = GLYPHS[char] ?? [];
    rows.forEach((bits, y) => {
      [...bits].forEach((bit, x) => {
        if (bit !== '1') return;
        const offset = ((y + GAP) * width + index * (GLYPH_WIDTH + GAP) + GAP + x) * 3;
        pixels.fill(245, offset, offset + 3);
      });
    });
  });
  const ppm = new Uint8Array(header.length + pixels.length);
  ppm.set(header);
  ppm.set(pixels, header.length);
  return { width, height, ppm };
}
