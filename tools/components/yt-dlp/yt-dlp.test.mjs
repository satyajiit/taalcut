describe('the hash-locked requirements', () => {
  const lock = [
    '# This file was autogenerated by uv via the following command:',
    'certifi==2026.10.19 \\',
    `    --hash=sha256:${hash('a')} \\`,
    `    --hash=sha256:${hash('b')}`,
    '    # via requests',
    "mutagen==1.48.1 ; sys_platform == 'darwin' \\",
    `    --hash=sha256:${hash('c')}`,
    '',
  ].join('\n');

  it('reads every pinned distribution with its marker and hashes', () => {
    assert.deepEqual(
      parseLock(lock).map(({ name, version, marker, hashes }) => ({ name, version, marker, hashes })),
      [
        { name: 'certifi', version: '2026.10.19', marker: undefined, hashes: [hash('a'), hash('b')] },
        { name: 'mutagen', version: '1.48.1', marker: "sys_platform == 'darwin'", hashes: [hash('c')] },
      ],
    );
    assert.equal(normaliseName('Charset_Normalizer'), 'charset-normalizer');
  });

  it('refuses an unpinned or unhashed line', () => {
    assert.throws(() => parseLock('requests>=2\n'), /not a pinned, hashed requirement/);
    assert.throws(() => parseLock('requests==2.34.2\n'), /requests==2.34.2 has no hashes/);
  });

  it('accepts a hosted sdist only when its sha256 is one the lock names', () => {
    const sources = { certifi: { version: '2026.10.19', pin: { sha256: hash('b') } } };
    assert.doesNotThrow(() => checkSourcesAgainstLock([lock], sources));
    const other = { certifi: { version: '2026.10.19', pin: { sha256: hash('d') } } };
    assert.throws(() => checkSourcesAgainstLock([lock], other), /sha256 is not in upstream's lock/);
    const missing = { websockets: { version: '17.2', pin: { sha256: hash('a') } } };
    assert.throws(
      () => checkSourcesAgainstLock([lock], missing),
      /websockets 17.2 is not in upstream's lock/,
    );
  });
});

describe('the licence inventory', () => {
  const base = '/py';
  const source = '/src/yt-dlp';
  const dist = (name, version, licence, files) => ({
    name,
    version,
    licenseExpression: licence,
    license: null,
    classifiers: [],
    licenseFiles: files.filter((f) => f.includes('LICENSE') || f.includes('COPYING')),
    files,
  });
  const report = {
    python: '3.14.9',
    base,
    source,
    collected: [
      '/venv/certifi/cacert.pem',
      '/venv/mutagen/__init__.py',
      `${base}/lib/libpython3.14.dylib`,
      `${source}/yt_dlp/__init__.py`,
    ],
    distributions: [
      dist('certifi', '2026.10.19', 'MPL-2.0', [
        '/venv/certifi/cacert.pem',
        '/venv/certifi-2026.10.19.dist-info/licenses/LICENSE',
      ]),
      dist('mutagen', '1.48.1', 'GPL-2.0-or-later', [
        '/venv/mutagen/__init__.py',
        '/venv/mutagen-1.48.1.dist-info/COPYING',
      ]),
      {
        ...dist('pyinstaller', '6.22.0', null, ['/venv/pyinstaller-6.22.0.dist-info/COPYING.txt']),
        license: DISTRIBUTIONS.pyinstaller.declared,
      },
      dist('pip', '25.3', 'MIT', ['/venv/pip/__init__.py']),
    ],
  };
  const pythonJson = {
    licenses: ['Python-2.0', 'CNRI-Python'],
    license_path: 'licenses/LICENSE.cpython.txt',
    build_info: {
      extensions: { _ssl: [{ licenses: ['Apache-2.0'], license_paths: ['licenses/LICENSE.openssl-3.txt'] }] },
    },
  };
  const tables = { ytDlpVersion: '2026.10.21', distributions: DISTRIBUTIONS, copyleft: COPYLEFT };

  it('finds the bundled distributions (the bootloader too) and marks the copyleft ones', () => {
    const { pieces, problems } = inventory(report, pythonJson, tables);
    assert.deepEqual(problems, []);
    assert.deepEqual(
      pieces.map((p) => `${p.name} ${p.version} ${p.spdx}${p.copyleft ? ' copyleft' : ''}`),
      [
        'yt-dlp 2026.10.21 Unlicense',
        'Python 3.14.9 Apache-2.0 AND CNRI-Python AND Python-2.0',
        'certifi 2026.10.19 MPL-2.0 copyleft',
        'mutagen 1.48.1 GPL-2.0-or-later copyleft',
        'pyinstaller 6.22.0 GPL-2.0-or-later WITH Bootloader-exception copyleft',
      ],
    );
    assert.deepEqual(pieces[1].licenseFiles, [
      'licenses/LICENSE.cpython.txt',
      'licenses/LICENSE.openssl-3.txt',
    ]);
    assert.doesNotThrow(() => checkCopyleftSet(pieces));
    assert.throws(
      () => checkCopyleftSet(pieces.slice(0, 3)),
      /copyleft pieces certifi 2026.10.19 but sources/,
    );
  });

  it('fails on an unknown file, an unreviewed distribution, a changed licence or a copyleft C library', () => {
    const changed = structuredClone(report);
    changed.collected.push('/elsewhere/x.so', '/venv/newdist/a.py');
    changed.distributions.push(dist('newdist', '1.0', 'MIT', ['/venv/newdist/a.py']));
    changed.distributions[0].licenseExpression = 'MPL-2.0 OR MIT';
    const gpl = { ...pythonJson, licenses: [...pythonJson.licenses, 'GPL-3.0-only'] };
    const { problems } = inventory(changed, gpl, tables);
    assert.deepEqual(problems, [
      'collected file from no known distribution: /elsewhere/x.so',
      'Python bundles a library under GPL-3.0-only',
      'certifi 2026.10.19 now declares "MPL-2.0 OR MIT", reviewed as "MPL-2.0"',
      'newdist 1.0 (MIT) is bundled but not reviewed in pins.mjs',
    ]);
  });

  it('reads a declared licence from the expression, the field or the classifiers', () => {
    assert.equal(declaredLicence({ licenseExpression: 'MIT', license: 'x', classifiers: [] }), 'MIT');
    assert.equal(declaredLicence({ license: 'BSD', classifiers: [] }), 'BSD');
    assert.equal(
      declaredLicence({
        classifiers: ['License :: OSI Approved :: BSD License', 'License :: Public Domain'],
      }),
      'OSI Approved :: BSD License; Public Domain',
    );
    assert.deepEqual(pythonLicences({}).licences, []);
  });

  it('writes one line per piece, the copyleft ones saying where their source is', () => {
    const text = inventoryText(
      [
        { name: 'certifi', version: '1', spdx: 'MPL-2.0', copyleft: true },
        { name: 'curl_cffi', version: '2', spdx: 'MIT', copyleft: false, bundles: 'libcurl' },
      ],
      'beside it',
    );
    assert.equal(
      text,
      'certifi 1: MPL-2.0 [copyleft: source hosted, beside it]\ncurl_cffi 2: MIT; bundles libcurl\n',
    );
  });

  it('pins a source for exactly the distributions reviewed as copyleft', () => {
    const copyleft = Object.entries(DISTRIBUTIONS)
      .filter(([, row]) => row.copyleft)
      .map(([name]) => name);
    assert.deepEqual(Object.keys(COPYLEFT_SOURCES).sort(), copyleft.sort());
  });
});

describe('the Taalcut variant', () => {
  const versionPy =
    "__version__ = '2026.10.21'\nRELEASE_GIT_HEAD = 'x'\nVARIANT = None\nUPDATE_HINT = None\n";

  it("names the variant and turns yt-dlp's updater into a hint", () => {
    const out = taalcutVersionPy(versionPy, '2026.10.21');
    assert.match(out, /^VARIANT = 'taalcut'$/m);
    assert.ok(out.includes(`UPDATE_HINT = '${UPDATE_HINT}'`));
  });

  it("refuses another release's version.py, or one it can't set", () => {
    assert.throws(() => taalcutVersionPy(versionPy, '2026.10.22'), /version.py is not 2026.10.22/);
    assert.throws(() => taalcutVersionPy("__version__ = '2026.10.21'\n", '2026.10.21'), /no VARIANT = None/);
  });
});

describe('the run check', () => {
  let dir;
  before(async () => {
    dir = await mkdtemp(join(tmpdir(), 'taalcut-ytdlp-test-'));
  });
  after(() => rm(dir, { recursive: true, force: true }));

  it('serves the fixture page and clip, ranges included', async () => {
    const fixture = await startFixture();
    try {
      const page = await (await fetch(fixture.url)).text();
      assert.ok(page.includes(`<title>${FIXTURE_TITLE}</title>`));
      const clipUrl = fixture.url.replace('index.html', 'clip.mp4');
      const range = await fetch(clipUrl, { headers: { range: 'bytes=10-19' } });
      assert.equal(range.status, 206);
      assert.deepEqual(Buffer.from(await range.arrayBuffer()), fixtureClip().subarray(10, 20));
      assert.equal((await fetch(fixture.url.replace('index.html', 'nope'))).status, 404);
    } finally {
      await fixture.close();
    }
    assert.deepEqual(fixtureClip(64), fixtureClip(64));
  });

  it("checks the printed title and path and the saved file's bytes", async () => {
    await writeFile(join(dir, 'clip.mp4'), fixtureClip());
    const fixture = await startFixture();
    await fixture.close();
    const good = `${FIXTURE_TITLE} (1)\n${join(dir, 'clip.mp4')}\n`;
    assert.deepEqual(await extractionProblems(good, { outDir: dir, clipSha256: fixture.clipSha256 }), []);
    const wrong = await extractionProblems(`other\n${join(dir, 'clip.webm')}\n`, {
      outDir: dir,
      clipSha256: fixture.clipSha256,
    });
    assert.equal(wrong.length, 2);
    const bytes = await extractionProblems(good, { outDir: dir, clipSha256: hash('0') });
    assert.match(bytes[0], /the saved file's sha256 is/);
  });

  it("runs without a config or cache and passes every parameter the fetcher's profile names", async () => {
    const args = extractionArgs('http://127.0.0.1:1/index.html', '/out');
    assert.deepEqual(args.slice(0, 3), ['--no-config', '--ignore-config', '--no-cache-dir']);
    assert.equal(args.at(-1), 'http://127.0.0.1:1/index.html');
    const params = new Map(
      sandboxParams({ scratch: '/s', home: '/h', executable: '/c/yt-dlp', componentDir: '/c' }),
    );
    assert.equal(params.get('PROGRAM_DIR'), '/c');
    assert.equal(params.get('COMPONENT_0'), '/c');
    assert.equal(params.get('TMPDIR'), '/s/tmp');
    const named = new Set(
      [...(await readFile(PROFILE, 'utf8')).matchAll(/\(param "(\w+)"\)/g)].map((m) => m[1]),
    );
    assert.deepEqual(
      [...named].filter((name) => !params.has(name)),
      [],
    );
  });
});
