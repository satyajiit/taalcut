import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as src from '../tokens/source.mjs';
import { apcaSelfTest, css, hex, ratio } from './colour-math.mjs';
import { gateReport, runGate } from './contrast-gate.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const tokensDir = join(here, '..', 'tokens');
const designDir = join(here, '..');
const THEMES = ['light', 'dark'];

// ---------- resolve every colour token per theme ----------

function resolveTheme(theme) {
  const n = src.neutrals[theme];
  const out = {};
  for (const [k, v] of Object.entries(n)) if (!k.startsWith('on-fill')) out[k] = v;
  for (const [k, v] of Object.entries(src.constants)) out[k] = v;
  const groups = { ...src.accents, ...src.kinds, ...src.status };
  for (const [name, def] of Object.entries(groups)) {
    const t = def[theme];
    out[name] = t.fill;
    out[`${name}-strong`] = t.strong;
    out[`${name}-soft`] = t.soft;
    // Text on the fill, and on the strong tone used as a fill (a hovered or pressed primary): whichever of the two
    // on-fill inks contrasts more.
    const onFill = (bg) => (ratio(n['on-fill-dark'], bg) >= ratio(n['on-fill-light'], bg) ? n['on-fill-dark'] : n['on-fill-light']);
    out[`${name}-ink`] = onFill(t.fill);
    out[`${name}-strong-ink`] = onFill(t.strong);
  }
  for (const [k, v] of Object.entries(src.logo[theme])) out[`logo-${k}`] = typeof v === 'string' ? out[v] : v;
  // The traffic controls: their own values, or another token's (one edit moves them to the palette).
  for (const [k, v] of Object.entries(src.windowControls[theme])) out[`window-${k}`] = typeof v === 'string' ? out[v] : v;
  return out;
}
const colours = Object.fromEntries(THEMES.map((t) => [t, resolveTheme(t)]));

// ---------- checks ----------

const selfTest = apcaSelfTest();
if (selfTest.length) {
  console.error(`APCA maths drifted from APCA-W3 0.1.9:\n  ${selfTest.join('\n  ')}`);
  process.exit(1);
}
const { checks, separations, gamut } = runGate(src, colours, THEMES);

// ---------- writers ----------

// Every generated file carries the licence header, in whatever form its format
// allows: a CSS comment, an HTML comment in Markdown, a property in JSON.
const SPDX = 'SPDX-License-Identifier: AGPL-3.0-or-later';
const COPYRIGHT = 'Copyright (C) 2026 Taalcut contributors';
const family = (stack) => stack.split(',')[0].trim().replace(/"/g, '');
const stamp = (file) => `/* ${SPDX} */
/* ${COPYRIGHT} */
/* Taalcut design tokens · file: ${file}
 * vibe: "${src.meta.vibe}" · paper: light ${css(src.neutrals.light.canvas)} / graphite: dark ${css(src.neutrals.dark.canvas)}
 * accents: marigold ${css(src.accents.marigold.dark.fill)} · rose · teal · violet (each with a job, see DESIGN.md)
 * kinds: ${Object.keys(src.kinds).join(' · ')} (category colours: formats, slot roles, fit; see DESIGN.md)
 * sans: ${family(src.fonts.sans)} · mono: ${family(src.fonts.mono)}
 * GENERATED by design/scripts/build-tokens.mjs from design/tokens/source.mjs. Do not edit by hand.
 */`;

function colourDecls(theme, indent = '  ') {
  const c = colours[theme];
  const lines = Object.entries(c).map(([k, v]) => `${indent}--color-${k}: ${css(v)};`);
  lines.push(`${indent}--color-scrim: ${src.scrim[theme]};`);
  for (const [k, v] of Object.entries(src.shadows[theme])) lines.push(`${indent}--shadow-${k}: ${v};`);
  lines.push(`${indent}--weight-body: ${src.bodyWeight[theme]};`);
  return lines.join('\n');
}
function roleDecls(indent = '  ') {
  const lines = [];
  for (const [role, accent] of Object.entries(src.roles)) {
    lines.push(`${indent}--color-${role}: var(--color-${accent});`);
    lines.push(`${indent}--color-${role}-strong: var(--color-${accent}-strong);`);
    lines.push(`${indent}--color-${role}-soft: var(--color-${accent}-soft);`);
    lines.push(`${indent}--color-${role}-ink: var(--color-${accent}-ink);`);
    lines.push(`${indent}--color-${role}-strong-ink: var(--color-${accent}-strong-ink);`);
  }
  lines.push(`${indent}--color-selection: var(--color-marigold-soft);`);
  lines.push(`${indent}--color-selected: var(--color-marigold-soft);`);
  return lines.join('\n');
}
// shadcn/ui's names, mapped onto Taalcut's roles, the same in every token file (UX4: tokens.css used to say
// accent was marigold and muted was ink-3). In shadcn, accent is the hover surface of a menu item, never one of
// Taalcut's four accents, and muted is a quiet surface.
const SHADCN = {
  background: 'canvas',
  foreground: 'ink',
  card: 'raised',
  'card-foreground': 'ink',
  popover: 'overlay',
  'popover-foreground': 'ink',
  'primary-foreground': 'marigold-ink',
  secondary: 'control',
  'secondary-foreground': 'ink',
  muted: 'sunken',
  'muted-foreground': 'ink-3',
  accent: 'hover',
  'accent-foreground': 'ink',
  destructive: 'danger',
  'destructive-foreground': 'danger-ink',
  border: 'rule',
  input: 'rule-strong',
  ring: 'focus',
  'chart-1': 'marigold',
  'chart-2': 'teal',
  'chart-3': 'violet',
  'chart-4': 'rose',
  'chart-5': 'info',
  'sidebar-foreground': 'ink-2',
  'sidebar-primary': 'marigold',
  'sidebar-primary-foreground': 'marigold-ink',
  'sidebar-accent': 'sidebar-hover',
  'sidebar-accent-foreground': 'ink',
  'sidebar-border': 'rule-subtle',
  'sidebar-ring': 'focus',
};
const aliasDecls = (indent = '  ') => Object.entries(SHADCN).map(([k, v]) => `${indent}--color-${k}: var(--color-${v});`).join('\n');
function staticDecls(indent = '  ') {
  const l = [];
  l.push(`${indent}--font-sans: ${src.fonts.sans};`);
  l.push(`${indent}--font-display: var(--font-sans);`);
  l.push(`${indent}--font-body: var(--font-sans);`);
  l.push(`${indent}--font-mono: ${src.fonts.mono};`);
  for (const [k, v] of Object.entries(src.weights)) l.push(`${indent}--font-weight-${k}: ${v};`);
  for (const [k, [size, lh, ls]] of Object.entries(src.text)) {
    l.push(`${indent}--text-${k}: ${size};`);
    l.push(`${indent}--text-${k}--line-height: ${lh};`);
    l.push(`${indent}--text-${k}--letter-spacing: ${ls};`);
  }
  for (const [k, v] of Object.entries(src.space)) l.push(`${indent}--space-${k}: ${v};`);
  l.push(`${indent}--radius: ${src.radius.base};`);
  for (const [k, v] of Object.entries(src.radius)) if (k !== 'base') l.push(`${indent}--radius-${k}: ${v};`);
  for (const [k, v] of Object.entries(src.motion.ease)) l.push(`${indent}--ease-${k}: ${v};`);
  for (const [k, v] of Object.entries(src.motion.dur)) l.push(`${indent}--dur-${k}: ${v};`);
  l.push(`${indent}--rule-hair: 1px;`);
  l.push(`${indent}--rule-fine: 2px;`);
  return l.join('\n');
}

const darkSelectors = (body) => `@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${body.replace(/^/gm, '  ')}
  }
}

:root[data-theme="dark"] {
  color-scheme: dark;
${body}
}`;

const tokensCss = `${stamp('tokens.css')}

/* Plain-CSS consumers (website, phone upload page, previews) import this file.
 * The app imports tailwind.css instead. Both come from the same source.
 *
 * Theme resolution:
 *   no data-theme        → follows prefers-color-scheme (in Electron, nativeTheme.themeSource)
 *   data-theme="light"   → light, whatever the system says
 *   data-theme="dark"    → dark, whatever the system says
 */

:root {
  color-scheme: light;
${staticDecls()}

  /* light (default) */
${colourDecls('light')}

  /* meaning layer: follows the theme automatically */
${roleDecls()}

  /* shadcn/ui names (accent is the hover surface, not an accent colour) */
${aliasDecls()}
}

${darkSelectors(colourDecls('dark'))}

@media (prefers-contrast: more) {
  :root {
    --color-ink-3: var(--color-ink-2);
    --color-rule: var(--color-rule-strong);
    --color-rule-subtle: var(--color-rule);
  }
}

@media (forced-colors: active) {
  :root {
    --color-focus: Highlight;
  }
}
`;

// Tailwind v4: register names in @theme with light values, override in @layer base.
const tailwindCss = `${stamp('tailwind.css')}

/* Import after Tailwind in the app's entry stylesheet:
 *   @import "tailwindcss";
 *   @import "<path>/design/tokens/tailwind.css";
 *   @import "<path>/design/tokens/base.css";
 * Tailwind's default palette, fonts, radii and shadows are reset, so only
 * Taalcut tokens exist as utilities (bg-canvas, text-ink-2, border-rule,
 * bg-marigold text-marigold-ink, text-violet-strong, rounded-xl, shadow-md…).
 */

@custom-variant dark {
  &:where([data-theme="dark"], [data-theme="dark"] *) {
    @slot;
  }
  @media (prefers-color-scheme: dark) {
    &:where(:root:not([data-theme="light"]), :root:not([data-theme="light"]) *) {
      @slot;
    }
  }
}

@theme static {
  --color-*: initial;
  --font-*: initial;
  --radius-*: initial;
  --shadow-*: initial;
  --text-*: initial;

${staticDecls()}

${colourDecls('light')}
}

/* Meaning roles, and shadcn/ui's names mapped onto Taalcut roles. Note: shadcn's "accent" is the
 * hover surface for menu items, not one of Taalcut's four accents. */
@theme inline {
${roleDecls()}
${aliasDecls()}
}

@layer base {
  :root {
    color-scheme: light;
  }

${darkSelectors(colourDecls('dark')).replace(/^/gm, '  ')}

  @media (prefers-contrast: more) {
    :root {
      --color-ink-3: var(--color-ink-2);
      --color-rule: var(--color-rule-strong);
      --color-rule-subtle: var(--color-rule);
    }
  }

  @media (forced-colors: active) {
    :root {
      --color-focus: Highlight;
    }
  }
}
`;

// DTCG 2025.10 shapes: colour objects with colorSpace/components, dimension objects.
const dtcgColour = ([L, C, H]) => ({ $type: 'color', $value: { colorSpace: 'oklch', components: [+(L / 100).toFixed(4), C, H], hex: hex([L, C, H]) } });
const dim = (v) => {
  const m = /^(-?[\d.]+)(rem|px)$/.exec(v);
  return m ? { $type: 'dimension', $value: { value: +m[1], unit: m[2] } } : { $type: 'string', $value: v };
};
// JSON has no comments: DTCG keeps extra data in $extensions; theme-meta.json is not DTCG.
const tokensJson = {
  $extensions: { 'org.taalcut.licence': { spdx: SPDX, copyright: COPYRIGHT } },
  $description: `Taalcut design tokens v${src.meta.version}. Generated from design/tokens/source.mjs. Colour has one group per theme; a DTCG resolver or Style Dictionary platform can map them to modes.`,
  color: Object.fromEntries(THEMES.map((t) => [t, Object.fromEntries(Object.entries(colours[t]).map(([k, v]) => [k, dtcgColour(v)]))])),
  font: {
    sans: { $type: 'fontFamily', $value: src.fonts.sans.split(',').map((s) => s.trim().replace(/"/g, '')) },
    mono: { $type: 'fontFamily', $value: src.fonts.mono.split(',').map((s) => s.trim().replace(/"/g, '')) },
  },
  fontWeight: Object.fromEntries(Object.entries(src.weights).map(([k, v]) => [k, { $type: 'fontWeight', $value: v }])),
  text: Object.fromEntries(Object.entries(src.text).map(([k, [size, lh, ls]]) => [k, { size: dim(size), lineHeight: dim(lh), letterSpacing: { $type: 'string', $value: ls } }])),
  space: Object.fromEntries(Object.entries(src.space).map(([k, v]) => [k, dim(v)])),
  radius: Object.fromEntries(Object.entries(src.radius).map(([k, v]) => [k, dim(v)])),
  duration: Object.fromEntries(Object.entries(src.motion.dur).map(([k, v]) => [k, { $type: 'duration', $value: { value: parseInt(v, 10), unit: 'ms' } }])),
  easing: Object.fromEntries(Object.entries(src.motion.ease).map(([k, v]) => [k, { $type: 'cubicBezier', $value: v.match(/[\d.]+/g).map(Number) }])),
};

const themeMeta = {
  $license: SPDX, $copyright: COPYRIGHT,
  $description: 'Window background per theme for Electron (prevents a flash before first paint) and theme-color for web pages. Generated.',
  canvas: { light: hex(colours.light.canvas), dark: hex(colours.dark.canvas) },
  viewer: hex(colours.light.viewer),
};

// ---------- report ----------

const fails = checks.filter((c) => !c.pass);
const sepFails = separations.filter((x) => !x.pass);
const report = gateReport({ src, colours, themes: THEMES, checks, separations, gamut, SPDX, COPYRIGHT });

writeFileSync(join(tokensDir, 'tokens.css'), tokensCss);
writeFileSync(join(tokensDir, 'tailwind.css'), tailwindCss);
writeFileSync(join(tokensDir, 'tokens.json'), JSON.stringify(tokensJson, null, 2) + '\n');
writeFileSync(join(tokensDir, 'theme-meta.json'), JSON.stringify(themeMeta, null, 2) + '\n');
writeFileSync(join(designDir, 'contrast-report.md'), report);

const gated = separations.filter((x) => x.gated).length;
console.log(
  `tokens built: ${checks.length - fails.length}/${checks.length} contrast checks pass (WCAG and APCA), ` +
    `${gated - sepFails.length}/${gated} dark separation floors hold, ${gamut.length} out of gamut`,
);
for (const f of fails)
  console.log(`  FAIL ${f.theme} ${f.fg} on ${f.bg}: ${f.ratio.toFixed(2)} (floor ${f.min}), Lc ${f.lc.toFixed(1)} (floor ${f.minLc ?? '-'})`);
for (const f of sepFails) console.log(`  FAIL ${f.theme} ${f.upper} over ${f.lower}: ΔL ${f.dL.toFixed(1)} < ${f.min}`);
for (const g of gamut) console.log(`  GAMUT ${g}`);
process.exit(fails.length || sepFails.length || gamut.length ? 1 : 0);
