/** Desktop window widths: the app's minimum, the default, and a wide display. */
const BREAKPOINTS = '1024,1280,1600';

const HEADER = `// SPDX-License-Identifier: AGPL-3.0-or-later
// Copyright (C) 2026 Taalcut contributors
// Generated by \`pnpm --filter @taalcut/renderer bones:capture\` (boneyard-js build). Do not edit.
`;

function run(command, args) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { cwd: ROOT, stdio: 'inherit' });
    child.on('error', reject);
    child.on('exit', (code) =>
      code === 0 ? resolve() : reject(new Error(`${command} exited with ${code}`)),
    );
  });
}

await run('pnpm', ['run', 'build']);
const server = await preview({ root: ROOT, preview: { port: PORT, strictPort: true, open: false } });
try {
  const pkg = createRequire(import.meta.url).resolve('boneyard-js/package.json');
  const cli = join(dirname(pkg), 'bin', 'cli.js');
  const urls = ROUTES.map((route) => `http://localhost:${PORT}${route}`);
  await run(process.execPath, [
    cli,
    'build',
    ...urls,
    '--out',
    OUT,
    '--breakpoints',
    BREAKPOINTS,
    '--no-scan',
    '--force',
  ]);
} finally {
  await server.close();
}

// The registry imports registerBones through @taalcut/ui (the renderer doesn't
// depend on boneyard-js at runtime) and carries the licence header.
const registry = join(ROOT, OUT, 'registry.ts');
const generated = readFileSync(registry, 'utf8')
  .replace(/^"use client"\n/, '')
  .replace(/^\/\/ Auto-generated.*\n/m, '')
  .replace(`from 'boneyard-js'`, `from '@taalcut/ui'`);
writeFileSync(registry, HEADER + generated);
process.stdout.write(`Wrote ${OUT}/registry.ts\n`);
