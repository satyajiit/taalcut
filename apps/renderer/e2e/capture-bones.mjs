  // The phone flow: the band and the QR hero while the session starts; the import history while it loads.
  '/library/phone/wifi',
  '/library/phone/transfers',
  // UX1 make: the project list and Exports (make-projects, make-exports).
  '/projects',
  '/renders',
  // UX4 tpl: the list, a template's four pages, Start from…'s cards, the community's list and a community
  // template, and Saved on Instagram.
  '/templates',
  '/templates/01K7C5M6Q85000000000000001',
