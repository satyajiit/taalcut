import { finish, formatTable } from './format.mjs';

const PACKAGE_HEADERS = ['name', 'version', 'licence', 'homepage'];
const COMPONENT_HEADERS = ['id', 'name', 'kind', 'version', 'licence', 'url', 'attribution'];

/**
 * NOTICE text. Stable for the same inputs: callers pass already-sorted rows.
 * No timestamps and no machine paths.
 */
export function renderDocument({ rows, vendored, components }) {
  const approved = rows.filter((row) => row.ok);
  const rejected = rows.filter((row) => !row.ok);
  const lines = [
    'Taalcut',
    'Copyright (C) 2026 Taalcut contributors',
    'Licensed under AGPL-3.0-or-later, see LICENSE.',
    'Additional permission for combining Taalcut code with GSAP and React Bits: LICENSE-EXCEPTIONS.md.',
    'Third-party code keeps its own terms; listed demonstration footage uses MEDIA-LICENSE.md.',
    'The installed app carries full vendor licence texts in Resources/licences, including GSAP with provenance,',
    'React Bits, page-mascot, earshot, Signalsmith, FluidAudio and fastcluster. Downloaded components carry their own notices.',
    '',
    'Generated by scripts/notice.mjs. Do not edit by hand. Regenerate with `pnpm notice`.',
    '',
    'Third-party packages',
    '',
    formatTable(
      PACKAGE_HEADERS,
      approved.map((row) => [row.name, row.version, row.license, row.homepage]),
    ),
  ];
  const noted = approved.filter((row) => row.note);
  if (noted.length > 0) {
    lines.push('', 'Notes');
    for (const row of noted) lines.push(`${row.name} ${row.version}: ${row.note}`);
  }
  for (const block of vendored) lines.push('', block.heading, block.body);
  lines.push(
    '',
    'Components',
    '',
    formatTable(
      COMPONENT_HEADERS,
      components.map((row) => [row.id, row.name, row.kind, row.version, row.spdx, row.url, row.attribution]),
    ),
  );
  if (rejected.length > 0) {
    lines.push(
      '',
      'Not on the allowlist',
      '',
      'These production dependencies are not approved. Remove them, or change the allowlist in scripts/licence-scan.mjs, then regenerate.',
      '',
      formatTable(
        PACKAGE_HEADERS,
        rejected.map((row) => [row.name, row.version, row.license, row.homepage]),
      ),
    );
  }
  return finish(lines);
}
