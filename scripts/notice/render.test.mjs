import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { describe, test } from 'node:test';
import { fileURLToPath } from 'node:url';
import { rowsFromReport } from '../licence-scan.mjs';
import { loadComponents } from './components.mjs';
import { renderDocument } from './render.mjs';
import { loadVendored } from './vendored.mjs';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const REACT_BITS_COMMIT = 'e2eb04d89d5be5a633dba7b2d4adfd274e053767';

function component(id, version, spdx, name) {
  return {
    id,
    name,
    version,
    kind: id === 'yt-dlp' ? 'tool' : 'model',
    licence: {
      spdx,
      notice: { url: `https://example.invalid/${id}`, size: 1, sha256: '0'.repeat(64) },
      attribution: `${name} credit`,
    },
    artifacts: [],
  };
}

describe('render from a fixture report', () => {
  test('is deterministic, sorted, and has one trailing newline', () => {
    const report = {
      'GPL-3.0-or-later': [
        { name: 'zz-later', versions: ['1.0.0'], license: 'MIT', homepage: 'https://example.invalid/z' },
      ],
      MIT: [
        { name: 'b', versions: ['2.0.0', '1.0.0'], license: 'MIT' },
        { name: 'a', versions: ['1.0.0'], license: 'MIT', homepage: 'https://example.invalid/a' },
        { name: '@taalcut/core', versions: ['0.0.0'], license: 'AGPL-3.0-or-later' },
      ],
    };
    const { rows } = rowsFromReport(report);
    const vendored = [{ heading: 'React Bits', body: `commit ${REACT_BITS_COMMIT}` }];
    const components = [
      {
        id: 'a',
        name: 'Aye',
        kind: 'tool',
        version: '2.0.0',
        spdx: 'Apache-2.0',
        url: 'https://example.invalid/a',
        attribution: 'A',
      },
      {
        id: 'b',
        name: 'Bee',
        kind: 'model',
        version: '1.0.0',
        spdx: 'MIT',
        url: 'https://example.invalid/b',
        attribution: 'B',
      },
    ];
    const first = renderDocument({ rows, vendored, components });
    const second = renderDocument({ rows, vendored, components });
    assert.equal(first, second);
    assert.equal(first.endsWith('\n'), true);
    assert.equal(first.endsWith('\n\n'), false);
    assert.equal(first.includes('\r'), false);
    assert.match(
      first,
      /Generated by scripts\/notice\.mjs\. Do not edit by hand\. Regenerate with `pnpm notice`\./,
    );
    assert.equal(first.includes('@taalcut/core'), false);
    const packages = first.slice(first.indexOf('\nThird-party packages\n'), first.indexOf('\nComponents\n'));
    assert.match(packages, /\na {2,}1\.0\.0[\s\S]*\nb {2,}1\.0\.0[\s\S]*\nb {2,}2\.0\.0/);
    const componentSection = first.slice(first.indexOf('\nComponents\n'));
    const aye = componentSection.indexOf('Aye');
    const bee = componentSection.indexOf('Bee');
    assert.ok(aye !== -1 && bee !== -1 && aye < bee);
    assert.equal(first.includes(process.cwd()), false);
  });
});

describe('component dedupe', () => {
  test('keeps one row per id, version, and SPDX, including GPL', () => {
    const dir = mkdtempSync(join(tmpdir(), 'taalcut-notice-'));
    try {
      const signed = {
        manifest: {
          components: [
            component('whisper', '1.0.0', 'MIT', 'from-signed'),
            component('yt-dlp', '2026.08.19', 'GPL-3.0-or-later', 'yt-dlp'),
          ],
        },
      };
      writeFileSync(
        join(dir, 'manifest.a.json'),
        JSON.stringify({ components: [component('whisper', '1.0.0', 'MIT', 'from-provisional')] }),
      );
      writeFileSync(join(dir, 'manifest.a.signed.json'), JSON.stringify(signed));
      writeFileSync(
        join(dir, 'manifest.example.json'),
        JSON.stringify({ components: [component('sherpa-onnx', '0.0.0', 'Apache-2.0', 'example')] }),
      );
      writeFileSync(join(dir, 'manifest.schema.json'), '{ "not": "a manifest" }');
      const rows = loadComponents(dir);
      assert.deepEqual(
        rows.map((row) => `${row.id}@${row.version} ${row.spdx} ${row.name}`),
        ['whisper@1.0.0 MIT from-provisional', 'yt-dlp@2026.08.19 GPL-3.0-or-later yt-dlp'],
      );
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});

describe('third_party in this repo', () => {
  test('contains the react-bits commit already in the tree', () => {
    const blocks = loadVendored(join(REPO, 'third_party'), REPO);
    const text = blocks.map((block) => `${block.heading}\n${block.body}`).join('\n');
    assert.match(text, new RegExp(REACT_BITS_COMMIT));
    assert.match(text, /never redistributed as a standalone kit/);
    assert.match(text, /503b4bd1bbf7220882de39fe8ae6716aae4132da/);
    assert.match(text, /David Haz/);
    assert.match(text, /76a44ed9180063bf4852b9dd724b656f4a828ac7/);
    assert.match(text, /Kamran Ahmed/);
    assert.match(text, /FluidAudio 0\.17\.7/);
    assert.match(text, /native\/mac-helper\/LICENSES\/FluidAudio-Apache-2\.0\.txt/);
    // LIB1-PLACE: CC BY 4.0's credit for the place names, its licence and link, and what was changed.
    assert.match(text, /GeoNames \(https:\/\/www\.geonames\.org\/\)/);
    assert.match(text, /CC BY 4\.0, https:\/\/creativecommons\.org\/licenses\/by\/4\.0\//);
    assert.match(text, /re-encoded for Taalcut/);
    // HFW1: HyperFrames' agent skill, pinned, under Apache-2.0, as the Designer's reference.
    assert.match(text, /heygen-com\/hyperframes at v0\.8\.209 \(commit `53c975966611e7012b09b6d46707c26511ea077d`\)/);
    assert.match(text, /licensed under Apache-2\.0/);
    // AGT2 sbx: Codex's Seatbelt base policy, unmodified at its pin, as the workspace shell profile's first block.
    assert.match(text, /openai\/codex, commit `696b4502dfaacd91133c3691a23dc91ae3b14bc9`, Apache-2\.0/);
    assert.match(text, /LICENSES\/Codex-Apache-2\.0\.txt/);
    const components = loadComponents(join(REPO, 'tools', 'components'));
    const fetchers = components.filter((row) => row.id === 'reference-fetcher');
    assert.equal(fetchers.length, 1);
    assert.equal(fetchers[0].spdx, 'GPL-3.0-or-later');
    assert.equal(
      components.some((row) => row.id === 'sherpa-onnx'),
      false,
    );
  });
});
