/** Every word (NFC, lowercase) that means a fixed action, to those actions. */
const WORD_TO_ACTIONS: ReadonlyMap<string, readonly ShotAction[]> = (() => {
  const map = new Map<string, ShotAction[]>();
  const add = (word: string, action: ShotAction) => {
    const key = word.normalize('NFC').toLowerCase();
    const list = map.get(key) ?? [];
    if (!list.includes(action)) map.set(key, [...list, action]);
  };
  for (const action of SHOT_ACTIONS) {
    add(action, action);
    for (const form of inflections(action)) add(form, action);
    for (const word of WORDS[action] ?? []) add(word, action);
  }
  for (const [word, action] of Object.entries(IRREGULAR)) add(word, action);
  return map;
})();

/** The fixed actions a word, or a run of words joined by spaces ("playing the guitar"), means. */
export function actionsOfWord(word: string): readonly ShotAction[] {
  return WORD_TO_ACTIONS.get(word.normalize('NFC').toLowerCase()) ?? [];
}
